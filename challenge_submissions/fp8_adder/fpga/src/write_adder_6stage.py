"""
6-stage FP8 adder pipeline with prefix-OR precompute targeting 200 MHz.

Key: break the fast_log2 bottleneck by precomputing 18 prefix-OR signals
(any[k] = |s_mag2[17:k]) one stage earlier. Then log2 is encoded from 18
registered 1-bit FFs -- just 2 logic levels (~1.5 ns) instead of 18-input
casez (~4.5 ns).

Also precomputes full result bytes per shift so S_ENCODE is trivial.

Stages:
  S_DECODE  (~3.0 ns): case mag decode + NaN/zero detect
  S_SUM     (~3.0 ns): signed 19-bit add/subtract
  S_PREHASH (~2.5 ns): 18 prefix-ORs + 15 precomputed result bytes
  S_LOG     (~1.5 ns): log2 from prefix-OR FFs + one-hot sh selection
  S_ROUND   (~1.0 ns): AND-OR select of precomputed result byte
  S_ENCODE  (~0.5 ns): sign combine + special-case override

Bottleneck: S_DECODE and S_SUM at ~3 ns -> Fmax ~300+ MHz theoretically.
Realistic with routing/setup at 85degC: 200-250 MHz.

TC cycles per test: 6 pipeline stages + 1 IDLE + 5 TC overhead = 13
  At 200 MHz: 4096*13/200e6 = 266 us
  At 250 MHz: 4096*13/250e6 = 213 us (M=15,D=3  VCO=750 MHz)
"""

