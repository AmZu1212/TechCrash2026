def do_round_expr(k):
    """Round-to-nearest-even for shift k, from individual s_mag2 bits.
    rm = s_mag2[k-1:0], hf = 1<<(k-1).
    rm > hf:  s_mag2[k-1] && |s_mag2[k-2:0]
    rm == hf: s_mag2[k-1] && ~|s_mag2[k-2:0]  AND ba_lsb = s_mag2[k]
    round = (rm>hf) | (rm==hf & ba_lsb)
          = s_mag2[k-1] & ( |s_mag2[k-2:0] | s_mag2[k] )
    Special k=0: no rounding bits below, no round.
    Special k=1: rm = s_mag2[0], hf=1. rm>hf: impossible (rm in {0,1}).
                 rm==hf: s_mag2[0]==1 AND ba_lsb=s_mag2[1]. round=s_mag2[0]&s_mag2[1].
    """
    if k == 0:
        return "1'b0"
    elif k == 1:
        return "(s_mag2[0] & s_mag2[1])"
    elif k == 2:
        return "(s_mag2[1] & (s_mag2[0] | s_mag2[2]))"
    else:
        lower_or = "|s_mag2[%d:0]" % (k-2)
        return "(s_mag2[%d] & (%s | s_mag2[%d]))" % (k-1, lower_or, k)

